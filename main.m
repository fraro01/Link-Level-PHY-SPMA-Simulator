%% TRANSMITTER PARAMATERS
% TX tuner delay: 1 microsecond, only when frequency changes
tunerDelay_s = 1e-6;
% Set the length of the packet in bits
packetLength = 1331; % bits
dutyCycle = 0.25; % percentage TX/RX (0,1]
numBursts = 28;
% FIXED OPTIMIZED PREAMBLE, orthogonality for its delayed copies
% the sync and the reference bits remain fixed for all bursts
preambleData = load('optimizedPreamble.mat', ...
                    'syncReference', ...  % mandatory load
                    'phaseReference', ... % mandatory load
                    'preambleInfo', ...
                    'M', ...
                    'LestDesign', ...
                    'channelEstMargin');
syncReference  = preambleData.syncReference;
phaseReference = preambleData.phaseReference;
% retrieve the saved indexing Codebook
indexingData = load('optimizedIndexing.mat', ...
                     'burstIndexCodebook', ...
                     'friendIndexCodeword');
burstIndexCodebook = indexingData.burstIndexCodebook;
friendIndexCodeword = indexingData.friendIndexCodeword;
rng('shuffle'); % set 'shuffle' to keep it random at each iteration, otherwise  
% e.g.: 4 allows to view some good MetricPlots
% Frequencies & RRC Parameters
fMin = 1435e6;
fMax = 1518e6;
numFrequencyChannels = 4;
rolloff = 0.35; % how much extra band we use for the RRC filter
filterSpan = 12; % RRC filter duration in symbols NOTE! the longer it lasts
% over time, the sharper it is over the frequencies.
% TLC formula for Symbol Rate: symbolRate = channelBandwidth/(1+rolloff)
symbolRate = ((fMax - fMin)/numFrequencyChannels)/(1 + rolloff);
samplesPerSymbol = 8; % number of samples per symbol
Fs = symbolRate * samplesPerSymbol; % sampling frequency, since we are 
% constructing the signal from the symbol to the the continuous time domain 
% we need more samples to represent one symbol.
cpLength = 3; % Must exceed the maximum channel delay in symbols, adding 
% the space for the cyclic prefix. NOTE! after the call to the 'Channel',
% there is an 'Assert' checking this condition.

%% CHANNEL PARAMETERS
% INTERFERERS
numInterferers = 0; % set the number of interferer nodes, NOTE! it 
% resembles an ALOHA network!
% BLANKING COMPENSATION
blankingPercentage = 0.0; % percentage with respect to the time 'txSignal' 
% representing the time occupied by the RX node while is transmitting

%% RECEIVER PARAMETERS
% This is just a safety margin chosen arbitrarily for safety indeed.
channelEstMargin = 2; % especially important for fractional delays, when 
% the significative energy of the channel symbol-spaced extends beyond the 
% prediction on the maximum delay. 

%% SIMULATION PARAMETERS
% amount of packet transmissions we want to simulate
metrics.packets = 10; % simulation cycles
show_metrics_plots = true; % whether to show the metric plots or not

% counters for storing values we use a MATLAB 'Structure'
metrics.detections = 0; % number of detections made by the CA-CFAR algorith
metrics.finalEncodedPacketErroredBits = 0; % errored bits in the encoded 
% packets
metrics.finalOriginalPacketErroredBits = 0; % errored bits in the original 
% packets
metrics.lostBurst = 0; % number of bursts lost
metrics.packetCompletelyReconstructed = false(1, metrics.packets); % with 0 
% errored bits
metrics.errRMS_runs = zeros(1, metrics.packets); 
metrics.errMax_runs = zeros(1, metrics.packets);
metrics.SINR_runs = zeros(1, metrics.packets); % SINR linear
metrics.EbN0_linear_runs = zeros(1, metrics.packets); % E_b/N_0 linear
metrics.EVM_runs = zeros(numBursts, metrics.packets); % EVM percentage

%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
%% SIMULATION LOOP
for i = 1:metrics.packets

    %% TRANSMITTER
    [packet, ... % original packet with random bits
     encodedPacket, ... % encoded packet above
     numEncodedBits,  ... % number of encoded bits due to Turbo Coding
     interleaverIndices, ... % for turbo decoder
     M, ... % modulation type
     bitsPerSymbol, ... 
     numPadBits8PSK, ... % padding bits for 8PSK
     symbolsPerBurst, ...
     symbolsPerBurstWithCP, ...
     modulatedBursts, ... % after 8PSK
     txSCFDEBursts, ... % after SCFDE
     frequencyChannels,...
     fCenter, ...
     relativeCarrierFrequencies, ... % equivalent baseband
     carrierForBurst, ... 
     burstTxTime, ...
     startTimes, ... % per burst
     txSignal, ... % FINAL TRANSMITTED SIGNAL
     numProtectedIndexBits, ...
     burstIndexCodebook, ...
     friendIndexCodeword, ...
     bitsPerBurst ...
    ] = transmitter.transmitter(...
     packetLength, ...
     numBursts, ... % how many bursts a packet is divided into
     syncReference, ... % fixed preamble above
     phaseReference, ... % fixed preamble above
     fMin, ... % lower boundary 
     fMax, ... % upper boundary 
     numFrequencyChannels, ... 
     rolloff, ... % RRC configuration
     filterSpan, ... % RRC configuration
     symbolRate, ...
     samplesPerSymbol, ...
     Fs, ... % sampling frequency
     cpLength, ... % Cyclic Prefix for SCFDE
     tunerDelay_s, ... % tuner delay for carriers
     dutyCycle, ...
     burstIndexCodebook, ...
     friendIndexCodeword ...
     );

    %{
    % Diagnostic
    disp('Reserved FRIEND index codeword:');
    disp(friendIndexCodeword);
    friendDistances = sum(burstIndexCodebook ~= friendIndexCodeword, 2);
    fprintf('Minimum FRIEND-to-desired Hamming distance = %d\n', ...
        min(friendDistances));
    %}

    %% CHANNEL
    [blankingMask, ... % blanking mask TxRxN
     rxSignal, ... % FINAL SIGNAL IN RX
     rxSignalImpaired, ...
     rxSignalAtAntenna, ...
     rxSignalWithInterference, ...
     interferer_waveform, ...
     pathGains, ...
     pathDelays_s, ...
     delay_max, ...
     friendBurstGroundTruth, ...
     max_interferer_delay ...
    ] = channel.channel(...
        txSignal, ... % signal in input
        numBursts, ...
        fMin, ...
        fMax, ...
        fCenter, ...
        carrierForBurst, ... % carrier frequencies per burst
        symbolRate, ...
        samplesPerSymbol, ...
        Fs, ...
        startTimes, ...
        symbolsPerBurstWithCP, ...
        filterSpan, ...
        rolloff, ...
        numFrequencyChannels, ...
        numInterferers, ...
        blankingPercentage, ...
        tunerDelay_s, ...
        dutyCycle, ...
        burstTxTime, ...
        syncReference, ...
        phaseReference, ...
        bitsPerBurst, ...
        numProtectedIndexBits, ...
        friendIndexCodeword, ...
        cpLength ...
        );
    
    % checking assertion in case of too low 'cpLength'
    minCpLength = ceil(delay_max/(1/symbolRate));
    assert(cpLength >= minCpLength, ...
    ['Cyclic prefix too short: cpLength = %d symbols, ' ...
     'but at least %d symbols are required by the maximum channel delay.'], ...
    cpLength, minCpLength);
    
    % CA-CFAR GROUND TRUTH
    % DESIRED bursts
    desiredGroundTruth.startTimes = startTimes(:);
    desiredGroundTruth.carrierForBurst = carrierForBurst(:);
    % FRIEND bursts
    friendGroundTruth = friendBurstGroundTruth;

    %% RECEIVER
    [errMax, ...
     errRMS, ...
     totalErroredBitsFromEncodedPacket, ... 
     totalErroredBitsFromOriginalPacket, ...
     burstDetected, ...
     numPilotSymbols, ...
     rxEqualizedBursts, ...
     H_est_bursts, ...
     vettore, ...             % diagnostic
     detections, ...          % diagnostic
     rxMatchedByChannel, ...  % diagnostic
     numDetectedBursts, ...
     intraBurstDiagnostic ... % diagnostic
    ] = receiver.receiver( ...
        rxSignal, ... % input signal
        blankingMask, ...
        numBursts, ...
        syncReference, ...
        phaseReference, ...
        cpLength, ...
        packet, ...
        encodedPacket, ...
        numEncodedBits, ...
        interleaverIndices, ...
        M, ...
        bitsPerSymbol, ...
        numPadBits8PSK, ...
        symbolsPerBurst, ...
        symbolsPerBurstWithCP, ...
        modulatedBursts, ...
        txSCFDEBursts, ...
        relativeCarrierFrequencies, ...    
        rolloff, ...
        filterSpan, ...
        symbolRate, ...
        samplesPerSymbol, ...
        Fs, ...
        show_metrics_plots, ...
        i, ...
        numProtectedIndexBits, ...
        burstIndexCodebook, ...
        delay_max, ...
        channelEstMargin, ...
        friendIndexCodeword ...
        );
    
    %% COMPUTE METRICS
    [sinr_linear, ... % SINR linear
     EbN0_linear, ... % E_b/N_0 linear
     evmPerBurst_percent ... % EVM percentage
    ] = CalculateMetrics.calculate_metrics( ... % static Class
        Fs, ...
        rxSignalImpaired, ...
        rxSignalAtAntenna, ...
        rxSignalWithInterference, ...
        interferer_waveform, ...
        packetLength, ...
        numBursts, ...
        burstDetected, ...
        modulatedBursts, ...
        numPilotSymbols, ...
        rxEqualizedBursts);
    % CA-CFAR FALSE DETECTIONS METRICS
    % Evaluate CA-CFAR detections against the physical burst ground truth.
    % Both DESIRED and FRIEND bursts are considered valid detections.
    % Each physical burst can be matched to at most one detection.    
    falseDetectionMetrics ...
      = CalculateMetrics.calculate_false_detections( ...
                                                detections, ...
                                                desiredGroundTruth, ...
                                                friendGroundTruth, ...
                                                fMin, ...
                                                fMax, ...
                                                numFrequencyChannels, ...
                                                Fs, ...
                                                filterSpan, ...
                                                cpLength, ...
                                                samplesPerSymbol, ...
                                                minCpLength, ...
                                                max_interferer_delay);

    %% UPDATE METRICS per Cycle
    if totalErroredBitsFromOriginalPacket == 0
        metrics.packetCompletelyReconstructed(i) = true;
    end    
    metrics.finalEncodedPacketErroredBits = ...
        metrics.finalEncodedPacketErroredBits + ...
            totalErroredBitsFromEncodedPacket;
    metrics.finalOriginalPacketErroredBits = ...
        metrics.finalOriginalPacketErroredBits + ...
            totalErroredBitsFromOriginalPacket;
    metrics.lostBurst = metrics.lostBurst + sum(~burstDetected);
    metrics.errRMS_runs(i) = errRMS;
    metrics.errMax_runs(i) = errMax;
    metrics.SINR_runs(i) = sinr_linear;
    metrics.EbN0_linear_runs(i) = EbN0_linear;
    metrics.EVM_runs(:,i) = evmPerBurst_percent;
    metrics.detections = metrics.detections + numDetectedBursts;
   
    % Metric Plots outputted only for the first iteration over the first
    % packet
    if show_metrics_plots == true && i == 1
        MetricPlots.frame_plot(bitsPerBurst, ...
                               cpLength, ...
                               syncReference, ...
                               phaseReference, ...
                               numProtectedIndexBits, ...
                               M);               
        MetricPlots.channelTaps_plot(pathDelays_s, ...
                                     pathGains);
        MetricPlots.channel_estimate(H_est_bursts, ...
                                     startTimes, ...
                                     Fs, ...
                                     numPilotSymbols, ...
                                     samplesPerSymbol, ...
                                     pathGains, ...
                                     symbolsPerBurst, ...
                                     burstDetected)
    end
end
