
clear;
close all;
clc;



%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
%                 OFFLINE PREAMBLE DESIGN                                 %
%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%

%% Preamble configuration
% NOTE! use the same values employed bu the Link-Level simulator!
M = 8; % extract this value from the 'transmitter.m'
channelEstMargin = 2; % extractc this from the 'main.m'
% From 'channel.m':
%   delay_max < 3*Tsymbol
% and 'receiver.m' uses:
%   Lest = ceil(delay_max/Tsymbol) + 1 + channelEstMargin
% Therefore the maximum Lest generated by the current channel model is:
LestDesign = 4 + channelEstMargin;

%% Monte Carlo search
% This script is executed OFFLINE, therefore we can afford
% a relatively large number of candidate sequences.
numTrials = 1e8; %1e6 %1e8

%% Generate optimized preamble and Save Permanently
[syncReference, ... phaseReference, ...
 preambleInfo] = generateOptimizedPreamble(M, ...
                                           LestDesign, ...
                                           numTrials);
% Save permanently
% save it as a 'mat' file, and their values will be retrieved by the 
% 'main.m'
save('optimizedPreamble.mat', ...
     'syncReference', ...
     'phaseReference', ...
     'preambleInfo', ...
     'M', ...
     'LestDesign', ...
     'channelEstMargin');

%% Plot normalized autocorrelation
figure;
stem(preambleInfo.autocorrelationLags, ...  % x-axis
     abs(preambleInfo.autocorrelation), ... % y-axis
     'filled');
grid on;
xlabel('Symbol delay');
ylabel('|R_x[\\ell]| / R_x[0]');
title(sprintf('Optimized 32-symbol 8-PSK Preamble - L_{est} = %d', ...
    LestDesign));

%% Plot Gram matrix
figure;
imagesc(abs(preambleInfo.gramMatrix));
axis image;
colorbar;
xlabel('Channel tap');
ylabel('Channel tap');
title('|A^H A| - Optimized Preamble');

%% Display final complete preamble
preambleBits = [syncReference; phaseReference];
fprintf('\nFINAL 96-BIT PREAMBLE:\n\n');
disp(preambleBits.');
fprintf('\nSaved in optimizedPreamble.mat\n\n');

%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%%
%                    END OFFLINE PREAMBLE DESIGN                          %
